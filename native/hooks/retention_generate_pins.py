"""Build-only extraction of exact retention guards; never reads user profiles."""
from __future__ import annotations
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
import pefile
from ghost_generate_pins import constants, require


def generate(runtime: Path, output: Path, proof: Path) -> None:
    source = Path(__file__).resolve().parents[2] / "modkit"
    specification = source / "message_retention_native.py"
    monitor = source / "message_retention_monitor.js"
    spec = constants(specification)
    js = monitor.read_text(encoding="utf8")
    # Keep role addresses tied to the reviewed callback expressions, while all
    # executable bytes, full hashes and slot targets come from the Python pins.
    roles = {}
    for role, expression in {
        "Event": r"base\.add\((0x[0-9a-f]+)\), \{onEnter: eventEnter",
        "Processor": r"base\.add\((0x[0-9a-f]+)\), \{onEnter: processorEnter",
        "OwnerCreate": r"base\.add\((0x[0-9a-f]+)\), \{onEnter:ownerEnter",
        "OwnerDestroy": r"base\.add\((0x[0-9a-f]+)\), \{onEnter:ownerDestroyed",
        "Rows": r"storage\.add\((0x[0-9a-f]+)\), \{onEnter:rowEnter",
    }.items():
        matches = re.findall(expression, js)
        require(len(matches) == 1, "Ambiguous retention callback: " + role)
        roles[role] = int(matches[0], 16)
    for role, predicate in (("First", "first"), ("Second", "second")):
        matches = re.findall(r"allocateRowGate\(storage\.add\((0x[0-9a-f]+)\),storage\.add\((0x[0-9a-f]+)\)," + predicate, js)
        require(len(matches) == 1, "Ambiguous retention gate: " + role)
        roles[role + "Gate"], roles[role + "Advance"] = (int(x, 16) for x in matches[0])
    lines = ["// Generated by retention_generate_pins.py; do not edit.", "#pragma once",
             '#include "ghost_internal.h"', "namespace valmax::retention::pins {",
             "using ghost::CodePin; using ghost::SlotPin; using ghost::ImagePin;"]
    report, namespace = {}, None
    for name, module in zip(("Core", "Storage"), spec["MODULES"]):
        path = runtime / module["name"]
        data = path.read_bytes()
        require(len(data) == module["moduleSize"], "Unsupported retention image size")
        canonical = data
        if hashlib.sha256(data).hexdigest() != module["moduleSha256"]:
            require(name == "Core", "Unsupported retention module hash")
            namespace = json.loads((runtime.parent / "build-proof.json").read_text())["namespace"]
            require(re.fullmatch(r"N[0-9A-F]{4}", namespace), "Invalid offline namespace")
            sys.path.insert(0, str(source))
            import build_mod
            entry = next(item for item in build_mod.specifications(["accounts", "privacy", "isolation"])
                         if item["relative_path"] == "core.dll")
            patch = next(item for item in entry["patches"] if item["id"] == "isolation.core_namespace_literal")
            at, original = patch["offset"], bytes.fromhex(patch["replacement"])
            require(data[at:at + len(original)] == namespace.encode("ascii") + b"\0", "Wrong offline namespace bytes")
            canonical = data[:at] + original + data[at + len(original):]
        require(hashlib.sha256(canonical).hexdigest() == module["moduleSha256"], "Unsupported retention canonical hash")
        pe = pefile.PE(data=data, fast_load=True)
        require(pe.FILE_HEADER.Machine == 0x8664 and pe.OPTIONAL_HEADER.Magic == 0x20B
                and pe.OPTIONAL_HEADER.SizeOfImage == module["imageSize"], "Unsupported retention PE layout")
        guards = []
        for pin in module["pins"]:
            guards.append((pin["rva"], pin["expected"]))
        for slot in module["slots"]:
            guards.append((slot["thunkRva"], slot["thunkExpected"]))
        for i, (rva, expected) in enumerate(guards):
            raw = bytes.fromhex(expected)
            section = pe.get_section_by_rva(rva)
            require(section is not None and section.Characteristics & 0x20000000
                    and pe.get_data(rva, len(raw)) == raw, "Retention code guard mismatch")
            lines.append(f"inline constexpr uint8_t k{name}Bytes{i}[] = {{{','.join(map(str, raw))}}};")
        lines.append(f"inline constexpr CodePin k{name}Guards[] = {{" + ",".join(
            f"{{{rva}u,k{name}Bytes{i}}}" for i, (rva, _) in enumerate(guards)) + "};")
        slots = []
        for slot in module["slots"]:
            rva, target = slot["vtableRva"] + slot["slot"], slot["thunkRva"]
            require(pe.get_data(rva, 8) == (pe.OPTIONAL_HEADER.ImageBase + target).to_bytes(8, "little"), "Retention slot mismatch")
            slots.append(f"{{{rva}u,{target}u}}")
        lines.append(f"inline constexpr SlotPin k{name}Slots[] = {{{','.join(slots)}}};")
        sha = hashlib.sha256(data).hexdigest()
        lines.append(f'inline constexpr ImagePin k{name} = {{"{sha}",{len(data)}ull,{module["imageSize"]}u,k{name}Guards,k{name}Slots}};')
        expected_roles = roles.keys() - {"Rows", "FirstGate", "FirstAdvance", "SecondGate", "SecondAdvance"} if name == "Core" else {"Rows", "FirstGate", "FirstAdvance", "SecondGate", "SecondAdvance"}
        require(all(roles[role] in {rva for rva, _ in guards} for role in expected_roles), "Unpinned retention callback")
        report[module["name"]] = {"sha256": sha, "canonicalSha256": module["moduleSha256"],
                                 "size": len(data), "imageSize": module["imageSize"],
                                 "codeGuards": len(guards), "vtableGuards": len(slots)}
    for role, rva in roles.items():
        lines.append(f"inline constexpr uint32_t k{role}Rva = {rva}u;")
    for key, value in spec["LIMITS"].items():
        lines.append(f"inline constexpr uint32_t k{key[0].upper()+key[1:]} = {value}u;")
    lines.append("}")
    output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not output.exists() or output.read_text(encoding="utf8") != text:
        output.write_text(text, encoding="utf8")
    proof.write_text(json.dumps({"schema": 1, "runtimeRoot": str(runtime.resolve()),
        "isolatedNamespace": namespace, "images": report, "roles": roles,
        "sourceSha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (specification, monitor)},
        "headerSha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "historySyncVerified": False, "realProfilesAccessed": False}, indent=2) + "\n", encoding="utf8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--proof", type=Path, required=True)
    args = parser.parse_args()
    generate(args.runtime_root, args.output, args.proof)
