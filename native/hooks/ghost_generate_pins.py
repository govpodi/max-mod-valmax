"""Generate native-only ghost pins from reviewed Python specifications and PE files.

Build tool only. Does not import or execute the old runtime, open profiles, or
publish a configurable pin format accepted by the production DLL.
"""
from __future__ import annotations
import argparse
import ast
import hashlib
import json
import re
import sys
from pathlib import Path
import pefile


def constants(path: Path) -> dict:
    result = {}
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try:
                result[node.targets[0].id] = ast.literal_eval(node.value)
            except (ValueError, TypeError):
                pass
    return result


def require(condition, message: str) -> None:
    if not condition:
        raise ValueError(message)


def generate(runtime: Path, output: Path, proof: Path) -> None:
    source = Path(__file__).resolve().parents[2] / "modkit"
    files = [source / "ghost_native.py", source / "ghost_unread_native.py"]
    core_spec, unread = constants(files[0]), constants(files[1])["PIN"]
    core_path, main_path = runtime / "core.dll", runtime / "max.exe"
    core, main = core_path.read_bytes(), main_path.read_bytes()
    require(len(core) == core_spec["CORE_FILE_SIZE"], "Unsupported core size")
    isolated_namespace = None
    if hashlib.sha256(core).hexdigest() != core_spec["CORE_SHA256"]:
        # Offline QA copies change only the keychain namespace. Prove the exact
        # reverse transformation to the same production core hash; never accept
        # an arbitrary core supplied by a manifest or a command-line hash.
        isolated_namespace = json.loads((runtime.parent / "build-proof.json").read_text())["namespace"]
        require(re.fullmatch(r"N[0-9A-F]{4}", isolated_namespace), "Invalid offline namespace")
        sys.path.insert(0, str(source))
        import build_mod
        core_record = next(item for item in build_mod.specifications(["accounts", "privacy", "isolation"]) if item["relative_path"] == "core.dll")
        patch = next(item for item in core_record["patches"] if item["id"] == "isolation.core_namespace_literal")
        offset, canonical = patch["offset"], bytes.fromhex(patch["replacement"])
        require(core[offset:offset + len(canonical)] == isolated_namespace.encode("ascii") + b"\0", "Namespace delta mismatch")
        normalized = core[:offset] + canonical + core[offset + len(canonical):]
        require(hashlib.sha256(normalized).hexdigest() == core_spec["CORE_SHA256"], "Unsupported core hash")
    images = [pefile.PE(data=data, fast_load=True) for data in (core, main)]
    require(all(pe.FILE_HEADER.Machine == 0x8664 and pe.OPTIONAL_HEADER.Magic == 0x20B for pe in images), "Unsupported PE architecture")
    require(images[0].OPTIONAL_HEADER.SizeOfImage == core_spec["CORE_IMAGE_SIZE"], "Unsupported core image size")
    require(images[1].OPTIONAL_HEADER.SizeOfImage > unread["vtableRva"] + 16, "Unsupported main image size")
    core_guards, main_guards, core_vtables, main_vtables = [], [], [], []
    for item in [*core_spec["WRAPPERS"], *core_spec["ONLINE"].values()]:
        core_guards.append((item["rva"], item["expected"]))
        if "thunkRva" in item:
            core_guards.append((item["thunkRva"], item["thunkExpected"]))
            core_vtables.append((item["vtableRva"] + item["slot"], item["thunkRva"]))
        if "serializerRva" in item:
            core_guards.append((item["serializerRva"], item["serializerExpected"]))
    core_guards.extend((item["rva"], item["expected"]) for item in unread["selfInfo"]["guards"])
    for prefix in ("reader", "model"):
        info = unread["selfInfo"]
        core_vtables.append((info[prefix + "VtableRva"] + info[prefix + "Slot"], info[prefix + "ThunkRva"]))
    main_guards.extend((item["rva"], item["expected"]) for item in unread["guards"])
    for slot, thunk, body in [(0, "destructorThunkRva", "destructorRva"), (8, "readThunkRva", "readRva")]:
        main_vtables.append((unread["vtableRva"] + slot, unread[thunk]))
        code = images[1].get_data(unread[thunk], 5)
        require(code[0] == 0xE9 and unread[thunk] + 5 + int.from_bytes(code[1:], "little", signed=True) == unread[body], "UI thunk target mismatch")
    for pe, guards, vtables in zip(images, (core_guards, main_guards), (core_vtables, main_vtables)):
        for rva, expected in guards:
            require(pe.get_data(rva, len(expected) // 2) == bytes.fromhex(expected), f"Code mismatch at {rva:x}")
        for rva, target in vtables:
            require(pe.get_data(rva, 8) == (pe.OPTIONAL_HEADER.ImageBase + target).to_bytes(8, "little"), f"Vtable mismatch at {rva:x}")
    lines = ["// Generated by ghost_generate_pins.py; do not edit.", "#pragma once", '#include "ghost_internal.h"', "namespace valmax::ghost::pins {"]
    for name, data, pe, guards, vtables in zip(("Core", "Main"), (core, main), images, (core_guards, main_guards), (core_vtables, main_vtables)):
        for i, (_, expected) in enumerate(guards):
            lines.append(f"inline constexpr uint8_t k{name}Bytes{i}[] = {{{','.join('0x' + expected[n:n+2] for n in range(0, len(expected), 2))}}};")
        lines.append(f"inline constexpr CodePin k{name}Guards[] = {{" + ",".join(f"{{{rva}u,k{name}Bytes{i}}}" for i, (rva, _) in enumerate(guards)) + "};")
        lines.append(f"inline constexpr SlotPin k{name}Slots[] = {{" + ",".join(f"{{{rva}u,{target}u}}" for rva, target in vtables) + "};")
        lines.append(f'inline constexpr ImagePin k{name} = {{"{hashlib.sha256(data).hexdigest()}",{len(data)}ull,{pe.OPTIONAL_HEADER.SizeOfImage}u,k{name}Guards,k{name}Slots}};')
    lines.append("inline constexpr uint32_t kWrapperRvas[] = {" + ",".join(str(item["rva"]) + "u" for item in core_spec["WRAPPERS"]) + "};")
    for key, value in unread.items():
        if isinstance(value, int) and key != "schema":
            lines.append(f"inline constexpr uint32_t k{key[0].upper()+key[1:]} = {value}u;")
    for key, value in unread["selfInfo"].items():
        if isinstance(value, int):
            lines.append(f"inline constexpr uint32_t k{key[0].upper()+key[1:]} = {value}u;")
    for key in ("login", "encoder", "ping"):
        lines.append(f"inline constexpr uint32_t k{key.title()}Rva = {core_spec['ONLINE'][key]['rva']}u;")
    lines.append("}")
    output.parent.mkdir(parents=True, exist_ok=True)
    header = "\n".join(lines) + "\n"
    if not output.exists() or output.read_text(encoding="utf-8") != header:
        output.write_text(header, encoding="utf-8")
    proof.write_text(json.dumps({"schema": 1, "runtimeRoot": str(runtime.resolve()), "isolatedNamespace": isolated_namespace, "canonicalCoreSha256": core_spec["CORE_SHA256"], "sourceSha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in files}, "headerSha256": hashlib.sha256(output.read_bytes()).hexdigest(), "images": {p.name: {"sha256": hashlib.sha256(data).hexdigest(), "size": len(data), "imageSize": pe.OPTIONAL_HEADER.SizeOfImage} for p, data, pe in zip((core_path, main_path), (core, main), images)}, "codeGuards": [len(core_guards), len(main_guards)], "vtableGuards": [len(core_vtables), len(main_vtables)], "realProfilesAccessed": False}, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--proof", type=Path, required=True)
    args = parser.parse_args()
    generate(args.runtime_root, args.output, args.proof)
