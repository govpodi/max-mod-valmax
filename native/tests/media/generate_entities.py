"""Development-only generation. Runtime never imports Python or opens files.

Named HTML5 entity data comes from Python's html.entities.html5 (PSF license),
which cites the WHATWG named-character-references list. Only data is copied.
The generated file is committed; normal CMake builds do not run this script.
"""
import hashlib
import html.entities
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[3]
rows = sorted(html.entities.html5.items())
canonical = json.dumps(rows, ensure_ascii=True, separators=(',', ':')).encode()
lines = ['// Generated by native/tests/media/generate_entities.py; do not edit.',
         '// Python html.entities HTML5 data, PSF license; WHATWG named references.',
         '// Canonical data SHA256: ' + hashlib.sha256(canonical).hexdigest(),
         'struct Entity { const char* name; const char* utf8; };',
         'static constexpr Entity Entities[] = {']
for key, value in rows:
    # Each UTF-8 byte has its own hex escape: no following hex digit ambiguity.
    encoded = ''.join('\\x%02x' % b for b in value.encode('utf-8'))
    lines.append('    {"' + key + '", "' + encoded + '"},')
lines += ['};', '']
(root/'native/media/html_entities.inc').write_text('\n'.join(lines), encoding='utf-8')
source = Path(html.entities.__file__)
license_file = root/'native/licenses/python-3.14.6-LICENSE.txt'
provenance = {'source':'https://github.com/python/cpython/blob/v3.14.6/Lib/html/entities.py',
    'python':sys.version,'entries':len(rows),'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),
    'canonicalDataSha256':hashlib.sha256(canonical).hexdigest(),
    'generatedSha256':hashlib.sha256((root/'native/media/html_entities.inc').read_bytes()).hexdigest(),
    'license':'../licenses/python-3.14.6-LICENSE.txt','licenseSha256':hashlib.sha256(license_file.read_bytes()).hexdigest(),
    'notice':'HTML5 named-character-reference data, from CPython under the PSF license. Not relicensed as ValMAX MIT code.'}
(root/'native/media/html-entities-provenance.json').write_text(json.dumps(provenance,indent=2)+'\n',encoding='utf-8')
