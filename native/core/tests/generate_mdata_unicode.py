"""Regenerate pinned Python Unicode semantics for the pure Rust MData codec.

Run with the Python used by modkit. No profiles, credentials or network access.
The generated source records Unicode version and generator SHA-256; the table
contains every scalar whose Python casefold differs from itself. Device names
need only uppercase mappings whose entire result is ASCII.
"""
from pathlib import Path
import hashlib
import unicodedata

ROOT = Path(__file__).resolve().parents[3]
TARGET = ROOT / "native/core/src/mdata_casefold.rs"


def escaped(value):
    return '"' + ''.join('\\u{%x}' % ord(c) for c in value) + '"'


def main():
    digest = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    folding, upper = [], []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        char = chr(code)
        folded = char.casefold()
        if folded != char:
            folding.append((code, folded))
        capital = char.upper()
        if not char.isascii() and capital.isascii():
            upper.append((code, capital))
    rows = [
        "// Generated by tests/generate_mdata_unicode.py; do not edit manually.",
        f"// Python Unicode {unicodedata.unidata_version}; generator SHA256 {digest}",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "const FOLD: &[(u32, &str)] = &[",
        *[f"    (0x{code:x}, {escaped(value)})," for code, value in folding],
        "];",
        "const ASCII_UPPER: &[(u32, &str)] = &[",
        *[f"    (0x{code:x}, {escaped(value)})," for code, value in upper],
        "];",
        "pub fn casefold(value: &str) -> String {",
        "    let mut result = String::with_capacity(value.len());",
        "    for c in value.chars() {",
        "        match FOLD.binary_search_by_key(&(c as u32), |entry| entry.0) {",
        "            Ok(index) => result.push_str(FOLD[index].1),",
        "            Err(_) => result.push(c),",
        "        }",
        "    }",
        "    result",
        "}",
        "pub fn ascii_upper(value: &str) -> Option<String> {",
        "    let mut result = String::with_capacity(value.len());",
        "    for c in value.chars() {",
        "        if c.is_ascii() { result.push(c.to_ascii_uppercase()); }",
        "        else {",
        "            let index = ASCII_UPPER.binary_search_by_key(&(c as u32), |entry| entry.0).ok()?;",
        "            result.push_str(ASCII_UPPER[index].1);",
        "        }",
        "    }",
        "    Some(result)",
        "}",
    ]
    TARGET.write_text('\n'.join(rows) + '\n', encoding='utf-8')
    print(f"Generated {len(folding)} folds, {len(upper)} non-ASCII-to-ASCII uppercase mappings; Unicode {unicodedata.unidata_version}")


if __name__ == '__main__':
    main()
